"""
Module containing funcs to sync data with Claude API.

Only Module that requires an internet connetion to perform the following:

1. Store/retrieve the Anthropic API key from OS keychain
2. Drain the sync_queue: for each queued session note or chat message,
ask Claude to
    (a) Extract skills/edges to merge into the flowchart,
    (b) Suggest recommendations
3. Handle ordinary chat replies.
"""

from __future__ import annotations
import json
from typing import Any, Optional, Dict, List
import keyring
from anthropic import Anthropic
import logging
import traceback

from osaeru.config import KEYRING_KEY, KEYRING_SERVICE, MODEL, FLOWCHART_SYSTEM_PROMPT
from osaeru import database as db

logger = logging.getLogger(__name__)


def get_api_key() -> Optional[str]:
    """Retrieves the Anthropic API key from the OS keychain.

    Returns:
        Optional[str]: The Anthropic API key if it exists, otherwise None.
    """
    return keyring.get_password(KEYRING_SERVICE, KEYRING_KEY)


def set_api_key(api_key: str) -> None:
    """Sets the Anthropic API key in the OS keychain.

    Args:
        api_key (str): The Anthropic API key to store.
    """
    keyring.set_password(KEYRING_SERVICE, KEYRING_KEY, api_key)


def _client() -> Anthropic:
    """Creates an Anthropic client using the stored API key.

    Raises:
        RuntimeError: If no Anthropic API key is stored in the OS keychain.

    Returns:
        Anthropic: An instance of the Anthropic client initialized
        with the stored API key.
    """
    api_key = get_api_key()
    if not api_key:
        raise RuntimeError(
            "No Anthropic API key stored. Prompt the user to enter one in "
            "Settings before calling anything in this module."
        )

    return Anthropic(api_key=api_key)


def _extract_json(text: str) -> Dict[str, Any]:
    cleaned = text.strip()
    if cleaned.startswith("```"):
        cleaned = cleaned.split("```")[1]
        if cleaned.startswith("json"):
            cleaned = cleaned[4:]
    
    return json.loads(cleaned.strip())


def analyse_session_note(
    notes: str, existing_flowchart: Dict[str, Any]
) -> Dict[str, Any]:
    """Analyses a session note and existing flowchart to extract
    new skills, edges, and recommendations.

    Args:
        notes (str): The session note text to be analysed.
        existing_flowchart (Dict[str, Any]): The current flowchart
        represented as a dictionary.

    Returns:
        Dict[str, Any]: A dictionary containing new skills, edges, and recommendations.
    """
    logger.debug(f"analyse_session_note called. Note length={len(notes)}, flowchart_nodes={len(existing_flowchart.get("nodes", []))}")
    client = _client()
    message = client.messages.create(
        model=MODEL,
        max_tokens=1000,
        system=FLOWCHART_SYSTEM_PROMPT,
        messages=[
            {
                "role": "user",
                "content": (
                    f"Existing flowchart:\n{json.dumps(existing_flowchart)}\n\n"
                    f"New session note:\n{notes}"
                ),
            }
        ],
    )
    logger.debug(f"Raw API response object: {message}")

    text = "".join(block.text for block in message.content if block.type == "text")
    logger.info(f"Raw text from Claude (first 500 chars): {text[:500]}")
    
    parsed = _extract_json(text)
    
    logger.info(
        f"""Parsed result: new_skills={len(parsed.get("new_skills", []))}, 
        new_edges={len(parsed.get("new_edges", []))}, 
        recommendations={len(parsed.get("recommendations", []))}
        """
    )

    return parsed


def chat_reply(history: List[Dict[str, str]], flowchart: Dict[str, Any]) -> str:
    """Creates a chat reply based on the conversation history and the current flowchart.

    Args:
        history (List[Dict[str, str]]): A list of dictionaries representing the
        conversation history, where each dictionary contains a "role"
        (either "user" or "assistant") and "content" (the message text).
        flowchart (Dict[str, Any]): The current flowchart represented as a dictionary.

    Returns:
        str: The assistant's reply generated by the Claude model.
    """
    client = _client()
    system = (
        "You are a supportive, knowledgeable jiu jitsu coach chatting with "
        "your student about their training. Be specific and practical. "
        f"Here is what you currently know about their skills: {json.dumps(flowchart)}"
    )
    message = client.messages.create(
        model=MODEL,
        max_tokens=800,
        system=system,
        messages=history,
    )

    return "".join(block.text for block in message.content if block.type == "text")


def run_sync(conn) -> int:
    """Runs the sync process to process pending items in the sync queue.

    Args:
        conn (_type_): Database connection.

    Returns:
        int: The number of items processed from the sync queue.
    """
    logger.info("Sync starting")
    processed = 0
    flowchart = db.get_flowchart(conn)

    pending = db.pending_sync_items(conn)
    logger.info(f"Found {len(pending)} pending sync item(s)")
    
    if not pending:
        logger.warning(
            "No pending items - nothing to sync. "
            "If you expected items here, check sync_queue table directly."
        )
    
    for item in pending:
        logger.info(f"Processing item queue id={item['id']} kind={item['kind']}")
        payload = json.loads(item["payload"])
        
        try:
            if item["kind"] == "session_note":
                result = analyse_session_note(payload["notes"], flowchart)
                
                for skill in result.get("new_skills", []):
                    logger.info(f"Upserting skill: {skill}")
                    db.upsert_skill(
                        conn,
                        skill["name"],
                        skill.get("category"),
                        skill.get("confidence"),
                        session_id=payload.get("session_id"),
                    )
                
                for edge in result.get("new_edges", []):
                    logger.info(f"Adding edge: {edge}")
                    db.add_skill_edge(
                        conn,
                        edge["from"],
                        edge["to"],
                        edge["relation"],
                    )
                
                for rec in result.get("recommendations", []):
                    logger.info(f"Adding recommendations: {rec}")
                    related = (db.upsert_skill(conn, rec["related_skill"]) if rec.get("related_skill") else None)
                    db.add_recommendation(conn, rec["text"], related)
                
                flowchart = db.get_flowchart(conn)
            
            elif item["kind"] == "chat_message":
                logger.debug(f"Skipping chat_message item id={item['id']} (handled live, not via queue)")
                
            db.mark_synced(conn, item["id"])
            processed += 1
            logger.info(f"Item id={item['id']} marked synced")
        
        except Exception:
            logger.error("Failed processing item id=%s:\n%s", item["id"], traceback.format_exc())
            raise
    
    logger.info(f"Sync finished, processed={processed}")
    
    return processed
